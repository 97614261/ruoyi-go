CREATE TABLE erp_shop (
 shop_id BIGINT NOT NULL AUTO_INCREMENT,
 tenant_id BIGINT NOT NULL,
 shop_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
