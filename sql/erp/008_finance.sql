 UNIQUE KEY uk_f8_payable_line (tenant_id,payable_id,receipt_line_id),
 KEY ix_f8_payable_line_receipt (tenant_id,receipt_id,purchase_line_id),
 KEY ix_f8_payable_line_head (tenant_id,payable_id,receipt_id),
