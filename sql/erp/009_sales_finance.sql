 receivable_id BIGINT NOT NULL,
 return_id BIGINT NOT NULL,
 order_id BIGINT NOT NULL,
 package_id BIGINT NOT NULL,
 return_no VARCHAR(64) NOT NULL,
 amount DECIMAL(20,4) NOT NULL,
